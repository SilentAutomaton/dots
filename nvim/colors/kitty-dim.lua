-- Dim variants are the palette colour pulled towards the background, so any
-- palette keeps the same quiet look without hand-picked values.
local function dim(color, amount)
  local function channel(hex, i)
    return tonumber(hex:sub(i, i + 1), 16)
  end
  local out = "#"
  for i = 2, 6, 2 do
    local bg = channel(p.background, i)
    out = out .. string.format("%02x", math.floor(bg + amount * (channel(color, i) - bg) + 0.5))
  end
  return out
end

